"""
Evaluation harness using DeepEval.
Generates quantified metrics: task completion, answer relevancy, hallucination.

Run:
    python agent/eval.py

Output: scores per test case + aggregate report printed to console.
Use these numbers when talking to the AI judge.

Test cases below are GENERATED by scaffold.py on question drop.
Add your own or modify them after first run.
"""

import asyncio
import sys
from pathlib import Path
from rich.console import Console
from rich.table import Table
from rich.panel import Panel
from dotenv import load_dotenv

load_dotenv()
sys.path.insert(0, str(Path(__file__).parent.parent))

console = Console()

# GENERATED_TEST_CASES  ← scaffold.py injects TEST_CASES_DATA here
# Fallback: placeholder cases used before question drop
TEST_CASES_DATA = [
    {
        "input": "Placeholder test case — will be replaced by scaffold.py",
        "expected_output": "A correct, complete answer to the task",
        "context": "",
        "label": "placeholder",
    }
]


# ── DeepEval setup ────────────────────────────────────────────────────────────

def run_eval() -> dict:
    try:
        from deepeval import evaluate
        from deepeval.metrics import (
            TaskCompletionMetric,
            AnswerRelevancyMetric,
            HallucinationMetric,
        )
        from deepeval.test_case import LLMTestCase
    except ImportError:
        console.print("[red]deepeval not installed. Run: pip install deepeval[/red]")
        sys.exit(1)

    from agent.agent import main as run_agent

    console.print(Panel(
        "[bold cyan]Running Evaluation[/bold cyan]\n"
        f"[dim]{len(TEST_CASES_DATA)} test cases | Metrics: TaskCompletion, AnswerRelevancy, Hallucination[/dim]"
    ))

    metrics = [
        TaskCompletionMetric(threshold=0.7, model="gpt-4o", include_reason=True),
        AnswerRelevancyMetric(threshold=0.7, model="gpt-4o", include_reason=True),
        HallucinationMetric(threshold=0.5, model="gpt-4o"),
    ]

    test_cases = []
    results_summary = []

    for case in TEST_CASES_DATA:
        console.print(f"[yellow]Running:[/yellow] {case['label']}")
        try:
            agent_result = asyncio.run(run_agent(case["input"]))
            actual_output = agent_result.answer
        except Exception as e:
            actual_output = f"ERROR: {e}"

        tc = LLMTestCase(
            input=case["input"],
            actual_output=actual_output,
            expected_output=case["expected_output"],
            context=[case["context"]] if case["context"] else [],
        )
        test_cases.append(tc)
        results_summary.append({
            "label": case["label"],
            "input": case["input"][:60] + "..." if len(case["input"]) > 60 else case["input"],
            "output": actual_output[:80] + "..." if len(actual_output) > 80 else actual_output,
        })

    eval_results = evaluate(test_cases, metrics)

    _display_results(results_summary, eval_results)
    return eval_results


def _display_results(summary: list[dict], eval_results) -> None:
    table = Table(title="Evaluation Results", show_lines=True)
    table.add_column("Test Case", style="cyan", max_width=20)
    table.add_column("Input", style="white", max_width=35)
    table.add_column("Output", style="green", max_width=40)

    for row in summary:
        table.add_row(row["label"], row["input"], row["output"])

    console.print(table)

    console.print("\n[bold]Aggregate Scores[/bold]")
    console.print("[dim]Use these numbers in your AI judge session[/dim]\n")

    try:
        for result in eval_results.test_results:
            for metric_data in result.metrics_data:
                status = "[green]PASS[/green]" if metric_data.success else "[red]FAIL[/red]"
                console.print(
                    f"  {status} {metric_data.name}: "
                    f"[bold]{metric_data.score:.2f}[/bold]"
                    + (f" — {metric_data.reason}" if metric_data.reason else "")
                )
    except Exception:
        console.print("[yellow]Could not parse detailed scores — check eval_results object[/yellow]")

    console.print(Panel(
        "[bold yellow]Judge-Ready Statement[/bold yellow]\n\n"
        "\"My agent was evaluated on [N] test cases using DeepEval's TaskCompletion, "
        "AnswerRelevancy, and Hallucination metrics with an LLM-as-judge approach. "
        "Results: [paste scores here]. I can show you the full trace in Phoenix.\"",
        border_style="yellow",
    ))


if __name__ == "__main__":
    run_eval()
